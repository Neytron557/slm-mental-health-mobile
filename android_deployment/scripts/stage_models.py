#!/usr/bin/env python3
"""
Stage converted model artifacts onto an Android device via ADB.

Copies artifacts generated by convert_models.py into /sdcard/Models/<model_name>.
Optionally copies the shared prompt file used for benchmarking.
"""

from __future__ import annotations

import argparse
import shlex
import subprocess
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence

import yaml


REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG = REPO_ROOT / "android_deployment" / "config" / "models.yml"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--config",
        type=Path,
        default=DEFAULT_CONFIG,
        help="Path to models.yml registry.",
    )
    parser.add_argument(
        "--artifacts-root",
        type=Path,
        help="Override artifacts root.",
    )
    parser.add_argument(
        "--device-model-root",
        default="/sdcard/Models",
        help="Directory on device where model folders are stored.",
    )
    parser.add_argument(
        "--adb",
        default="adb",
        help="adb binary to use.",
    )
    parser.add_argument(
        "--models",
        nargs="*",
        help="Optional subset of model names to stage.",
    )
    parser.add_argument(
        "--backends",
        nargs="+",
        default=["ort-genai"],
        help="Which backend subfolders to push (matches artifacts/<model>/<backend>).",
    )
    parser.add_argument(
        "--append-backend",
        action="store_true",
        help="Append backend name as a subdirectory on device (useful when staging multiple builds).",
    )
    parser.add_argument(
        "--prompt-file",
        type=Path,
        default=REPO_ROOT / "android_deployment" / "prompts" / "mental_health_eval.txt",
        help="Prompt file to push alongside models.",
    )
    parser.add_argument(
        "--prompt-destination",
        default="/sdcard/Models/prompts.txt",
        help="Device path for the prompt file.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print actions without executing adb commands.",
    )
    return parser.parse_args()


def load_registry(config_path: Path) -> Dict:
    with config_path.open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def run(cmd: Sequence[str], *, dry_run: bool) -> None:
    cmd_str = " ".join(shlex.quote(part) for part in cmd)
    print(f"[adb] {cmd_str}")
    if dry_run:
        return
    subprocess.run(cmd, check=True)


def iter_artifacts(
    artifacts_root: Path,
    model_name: str,
    backends: Iterable[str],
) -> List[Path]:
    found = []
    for backend in backends:
        candidate = artifacts_root / model_name / backend
        if candidate.exists():
            found.append(candidate)
        else:
            print(f"[warn] Missing artifacts for {model_name}/{backend} -> {candidate}")
    return found


def push_directory(
    adb: str,
    source_dir: Path,
    device_dir: str,
    *,
    dry_run: bool,
) -> None:
    run([adb, "shell", f"mkdir -p {device_dir}"], dry_run=dry_run)
    for item in source_dir.iterdir():
        dst = f"{device_dir}/{item.name}"
        run([adb, "push", str(item), dst], dry_run=dry_run)


def push_prompt(
    adb: str,
    source: Path,
    destination: str,
    *,
    dry_run: bool,
) -> None:
    if not source.exists():
        print(f"[warn] Prompt file not found: {source}")
        return
    run([adb, "push", str(source), destination], dry_run=dry_run)


def main() -> None:
    args = parse_args()
    registry = load_registry(args.config)
    artifacts_root = (
        args.artifacts_root
        or (REPO_ROOT / registry.get("artifacts_root", "android_deployment/artifacts"))
    ).resolve()

    models = registry.get("models", [])
    selected = set(args.models) if args.models else None

    for entry in models:
        if selected and entry["name"] not in selected:
            continue
        paths = iter_artifacts(artifacts_root, entry["name"], args.backends)
        for src in paths:
            device_dir = f"{args.device_model_root}/{entry['name']}"
            if args.append_backend:
                device_dir = f"{device_dir}/{src.name}"
            print(f"[stage] {entry['name']} ({src.name}) -> {device_dir}")
            push_directory(args.adb, src, device_dir, dry_run=args.dry_run)

    if args.prompt_file:
        print(f"[stage] prompt -> {args.prompt_destination}")
        push_prompt(args.adb, args.prompt_file, args.prompt_destination, dry_run=args.dry_run)


if __name__ == "__main__":
    main()
